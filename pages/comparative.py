import plotly.express as px
import streamlit as st

from equipment import comparative as C
from equipment import db, ui

ui.banner("both", "Comparative Analysis")
ui.note("The two datasets are <b>independent</b>: different observation units, label definitions and sampling. They share "
        "no identifiers and are never joined. Raw failure counts are not compared; only proportions with their own "
        "denominators are shown side by side, and they are <b>not directly comparable</b>.")

try:
    conn = db.connect(read_only=True)
except db.DatabaseNotFoundError as exc:
    st.error(str(exc))
    st.stop()
try:
    counts = C.record_counts(conn)
    quality = C.quality_summary(conn)
    props = C.failure_proportions(conn)
finally:
    conn.close()

st.subheader("1. Dataset sizes and sources")
if counts["Rows"].sum() == 0:
    ui.empty_state("No data loaded yet - use Module 01 of each dataset.")
else:
    fig = px.bar(counts, x="Table", y="Rows", color="Dataset", log_y=True, text="Rows",
                 title="Rows per table (log scale: units differ - telemetry rows are hourly readings, AI4I rows are records)")
    ui.show_fig(fig, key="cmp_rows")
    ui.show_table(counts)

st.subheader("2. Data-quality summary (from the load logs)")
if quality.empty:
    ui.empty_state("No load history yet.")
else:
    ui.show_table(quality)

st.subheader("3. Failure-label definitions")
ui.show_table(C.DEFINITIONS)

st.subheader("4. Failure proportions (each with its own denominator)")
if props.empty:
    ui.empty_state()
else:
    ui.show_table(props)
    st.caption("Azure counts failure *events* against hourly machine observations; AI4I counts failed *records* among independent "
               "records. A machine-hour and an AI4I record are different units, and the datasets were generated by different "
               "processes, so a higher or lower percentage in one says nothing about the other.")

st.subheader("5. Supported analytics")
ui.show_table(C.SUPPORTED)

st.subheader("6. Limitations")
for title, items in C.LIMITATIONS.items():
    with st.expander(title if title != "Together" else "Comparing the two datasets", expanded=(title == "Together")):
        for it in items:
            st.markdown(f"- {it}")
st.caption("Azure machine-level risk scores and AI4I record-level indicators are built from different inputs and are "
           "deliberately not compared.")
